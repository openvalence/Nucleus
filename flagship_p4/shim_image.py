# PlatformIO pre-script of the flagship_p4_barnacle env only: builds
# barnacle_shim (its own project, ../barnacle_shim) and hands its app image to
# this build, which embeds it so the P4 can keep the helper up to date over
# the barnacle link (bd val-omh3.7).
#
# Writes $BUILD_DIR/barnacle_shim/barnacle_shim.bin (src/CMakeLists.txt embeds
# it) and barnacle_shim_image.h beside it (its version and digest). Both are
# build products: never committed. FAILS the build, never embeds a stale or
# missing image: a failed shim build, an image that is not an ESP32 app with
# its SHA-256 appended, or a kShimVersion it cannot read.
import hashlib
import os
import re
import subprocess

Import("env")

project_dir = env.subst("$PROJECT_DIR")
shim_dir = os.path.normpath(os.path.join(project_dir, "..", "barnacle_shim"))
out_dir = os.path.join(env.subst("$BUILD_DIR"), "barnacle_shim")
built = os.path.join(shim_dir, ".pio", "build", "barnacle_shim", "firmware.bin")


def fail(why):
    print("\nshim_image: %s; the barnacle image is not built without its helper's copy.\n" % why)
    env.Exit(1)


child_env = {k: v for k, v in os.environ.items() if not k.startswith("PLATFORMIO_") or k == "PLATFORMIO_CORE_DIR"}
print("shim_image: building barnacle_shim")
if subprocess.run([env.subst("$PYTHONEXE"), "-m", "platformio", "run", "-d", shim_dir, "-e", "barnacle_shim"],
                  env=child_env).returncode != 0:
    fail("pio run -d barnacle_shim failed")
if not os.path.isfile(built):
    fail("no %s after the shim build" % built)

image = open(built, "rb").read()
# esp_image_header_t: magic 0xE9 at 0, chip_id at 12 (0 = ESP32), hash_appended at 23.
if len(image) <= 64 or image[0] != 0xE9 or image[12] | (image[13] << 8) != 0 or image[23] != 1:
    fail("%s is not an ESP32 app image with its SHA-256 appended" % built)
if hashlib.sha256(image[:-32]).digest() != image[-32:]:
    fail("%s: its last 32 bytes are not the SHA-256 of the rest" % built)

source = open(os.path.join(shim_dir, "src", "main.cpp"), encoding="utf-8").read()
versions = re.findall(r"^constexpr uint8_t kShimVersion = (\d+);", source, re.MULTILINE)
if len(versions) != 1:
    fail("kShimVersion not found exactly once in barnacle_shim/src/main.cpp")

digest = image[-32:]
header = (
    "// Generated by flagship_p4/shim_image.py on every barnacle build: never edit, never commit.\n"
    "#pragma once\n"
    "#define BARNACLE_SHIM_VERSION %s\n"
    "#define BARNACLE_SHIM_BYTES %d\n"
    "#define BARNACLE_SHIM_DIGEST {%s}\n"
    % (versions[0], len(image), ", ".join("0x%02x" % b for b in digest))
)


def write_if_changed(path, data):
    if os.path.isfile(path) and open(path, "rb").read() == data:
        return
    with open(path, "wb") as f:
        f.write(data)


os.makedirs(out_dir, exist_ok=True)
write_if_changed(os.path.join(out_dir, "barnacle_shim.bin"), image)
write_if_changed(os.path.join(out_dir, "barnacle_shim_image.h"), header.encode("ascii"))
print("shim_image: helper shim v%s, %d B, digest %s" % (versions[0], len(image), digest[:8].hex()))
